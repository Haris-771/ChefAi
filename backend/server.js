import express from 'express';
import cors from 'cors';
import { OpenAI } from 'openai';
import 'dotenv/config';

const app = express();
const PORT = process.env.PORT || 5000;
const API_KEY = process.env.GROQ_API;

app.disable('x-powered-by');
app.use(cors());
app.use(express.json({ limit: '1mb' }));

if (!API_KEY) {
  throw new Error('Missing API in environment variables.');
}

const openai = new OpenAI({
  apiKey: API_KEY,
  baseURL: 'https://api.groq.com/openai/v1'
})

const normalizeIngredients = (ingredients) => {
  if (Array.isArray(ingredients)) {
    return ingredients
      .map((item) => String(item).trim())
      .filter(Boolean);
  }

  if (typeof ingredients === 'string') {
    return ingredients
      .split(/[\n,]/)
      .map((item) => item.trim())
      .filter(Boolean);
  }

  return [];
};

const extractJson = (rawText) => {
  const text = typeof rawText === 'string' ? rawText : '';

  if (!text) {
    throw new Error('No recipe generated by AI.');
  }

  const cleaned = text.replace(/```json|```/gi, '').trim();
  const start = cleaned.indexOf('{');
  const end = cleaned.lastIndexOf('}');

  if (start !== -1 && end !== -1 && end > start) {
    return cleaned.slice(start, end + 1);
  }

  return cleaned;
};

const isValidRecipe = (recipe) =>
  recipe &&
  typeof recipe.recipeName === 'string' &&
  Array.isArray(recipe.ingredients) &&
  Array.isArray(recipe.instructions);

app.get('/health', (_req, res) => {
  res.json({ status: 'ok' });
});

app.post('/api/recipe', async (req, res) => {
  try {
    const ingredients = normalizeIngredients(req.body?.ingredients);

    if (!ingredients.length) {
      return res.status(400).json({ error: 'No ingredients provided' });
    }

    const ingredientText = ingredients.join(', ');

    const prompt = `You are a professional chef. The user has these ingredients: "${ingredientText}".
Create a delicious recipe using them.
Return ONLY valid JSON with this exact structure:
{
  "recipeName": "Name of the Dish",
  "ingredients": ["ingredient 1 with measurements", "ingredient 2 with measurements"],
  "instructions": ["Step 1 explanation", "Step 2 explanation"]
}`;

    const response = await openai.chat.completions.create({
      model: 'openai/gpt-oss-120b',
      messages: [{ role: 'user', content: prompt }],
      max_tokens: 700,
      temperature: 0.7,
    });

    const rawText = response?.choices[0]?.message?.content ?? '';
    const parsedRecipe = JSON.parse(extractJson(rawText));

    if (!isValidRecipe(parsedRecipe)) {
      return res.status(500).json({ error: 'AI returned an invalid recipe format.' });
    }

    return res.json(parsedRecipe);
  } catch (error) {
    console.error('Error on server:', error);
    return res.status(500).json({ error: 'Failed to generate a recipe from AI.' });
  }
});

app.listen(PORT, () => {
  console.log(`🚀 Backend server running on http://localhost:${PORT}`);
});
